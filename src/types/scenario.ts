import type { AppLanguage } from "./language";
import type { ScenarioDifficulty } from "@/lib/scenarios/scenarioLibrary";
import type { MediaAsset } from "./media";
import type { ScenarioSpeaker } from "./simulation";
import type { CastMember } from "./cast";
import type { SceneId } from "./scene";

/** One of OpenAI's preset TTS voices. */
export type OpenAiVoiceId =
  | "alloy"
  | "ash"
  | "ballad"
  | "coral"
  | "echo"
  | "fable"
  | "nova"
  | "onyx"
  | "sage"
  | "shimmer"
  | "verse";

/**
 * The voice a single character speaks with. Pinned once when the scenario is
 * created so the same character never drifts between perceived genders, and
 * carried through every TTS call for that speaker.
 */
export type CharacterVoice = {
  voiceId: OpenAiVoiceId;
  /** Baseline emotional state, used to build the TTS delivery instruction. */
  emotion: string;
};

/**
 * Whether the patient is alive when the conversation starts. A sedated,
 * unconscious or dying patient is still "alive"; "deceased" means the trainee is
 * declaring or explaining a death and speaks only to the people around them.
 */
export type PatientStatus = "alive" | "deceased";

export type Scenario = {
  id: string;
  title: string;
  setting: string;
  /*
   * Which illustrated room the simulation is staged in. The free-text setting
   * above stays the words shown to the trainee; this is the picture. Optional
   * so older scenarios load, and those are matched from their setting text by
   * sceneForScenario().
   */
  settingKind?: SceneId;
  summary: string;
  patientProfile: string;
  /*
   * Its own field rather than a value of patientEmotion. Before it existed the
   * model wrote "Deceased" into the emotion slot, so the brief showed a death
   * as if it were a feeling and nothing downstream could tell the two apart.
   * Optional so scenarios saved before it still load; read it through
   * getPatientStatus(), which recognises those older cases.
   */
  patientStatus?: PatientStatus;
  /** Empty when the patient is deceased: there is no emotional state to play. */
  patientEmotion: string;
  familyEmotion?: string;
  traineeObjective: string;
  communicationChallenge: string;
  startingSituation: string;
  firstPrompt: string;
  suggestedTurns: number;
  endingCondition: string;
  evaluationCriteria: string[];
  defaultEvaluationCriteria?: string[];
  mediaAssets?: MediaAsset[];
  /** Optional so scenarios saved before voice pinning still load. */
  characterVoices?: Partial<Record<ScenarioSpeaker, CharacterVoice>>;
  /*
   * Who is in the room: one entry per speaking role, patient included even when
   * deceased (their gender still shapes how everyone talks about them). Drives
   * the simulation stage's portraits and the gender of each pinned voice.
   * Optional so scenarios generated before it still load; the stage falls back
   * to a plain role tile for them.
   */
  cast?: CastMember[];

  /*
   * Progress-tracking metadata. Set on the client from the library case the
   * trainer picked and the tier they chose — NEVER generated by the model. If
   * these came out of Gemini it would invent a difficulty for every scenario
   * and the cohort comparison buckets would be fiction.
   *
   * All optional so scenarios saved before this existed still load.
   */

  /** The `LibraryScenario.id` this was generated from, if any. */
  libraryId?: string;
  /** Track name, e.g. "Breaking bad news". Carried from the library case. */
  category?: string;
  /** Chosen by the trainer; defaults to the library case's tier. */
  difficulty?: ScenarioDifficulty;

  /*
   * The language this scenario was generated in, and therefore the language its
   * roleplay, feedback, speech-to-text and read-aloud all run in.
   *
   * Pinned here rather than read from the reader's UI preference: a case is an
   * exercise, and translating it after the fact would change what was set and
   * leave a saved run's transcript no longer matching its own scenario.
   * Optional so scenarios saved before this existed still load as English.
   */
  language?: AppLanguage;
};
